#!/usr/bin/env python3
"""
Extract TSQX snippets preserved inside Evan Chen handout .tex files.

This script only extracts blocks that explicitly contain preserved TSQX text.
If a figure only contains a placeholder such as "Source generated by TSQ",
it is reported as missing-source instead of hallucinating a reconstruction.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


BEGIN_ASY = r"\begin{asy}"
END_ASY = r"\end{asy}"


def slugify(text: str) -> str:
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = re.sub(r"-+", "-", text).strip("-")
    return text or "figure"


def clean_caption(raw: str) -> str:
    text = re.sub(r"\\[a-zA-Z]+\{([^{}]*)\}", r"\1", raw)
    text = re.sub(r"\\[a-zA-Z]+", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def extract_tsqx_from_comment(comment: str) -> str | None:
    lines = []
    started = False
    for raw in comment.splitlines():
        line = raw.rstrip()
        if "TSQX:" in line:
            started = True
            continue
        if not started:
            continue
        if "https://github.com" in line:
            continue
        if line.lstrip().startswith("+---"):
            continue
        if line.lstrip().startswith("|"):
            continue
        line = line.strip()
        if not line:
            continue
        lines.append(line)
    if lines:
        return "\n".join(lines) + "\n"
    return None


def nearest_caption(tex: str, end_pos: int) -> str | None:
    tail = tex[end_pos : end_pos + 600]
    match = re.search(r"\\caption\{(.*?)\}", tail, re.S)
    if match:
        return clean_caption(match.group(1))
    return None


def iter_asy_blocks(tex: str):
    pattern = re.compile(r"\\begin\{asy\}(.*?)\\end\{asy\}", re.S)
    for match in pattern.finditer(tex):
        yield match.start(), match.end(), match.group(1)


def main() -> int:
    parser = argparse.ArgumentParser(description="Extract preserved TSQX examples from Evan handouts.")
    parser.add_argument("source_root", help="Root handouts directory")
    parser.add_argument("output_root", help="Output directory for dataset")
    args = parser.parse_args()

    source_root = Path(args.source_root).expanduser().resolve()
    output_root = Path(args.output_root).expanduser().resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    manifest: list[dict] = []
    extracted_dir = output_root / "cases"
    extracted_dir.mkdir(parents=True, exist_ok=True)

    for tex_path in sorted(source_root.rglob("*.tex")):
        tex = tex_path.read_text(errors="ignore")
        relative = tex_path.relative_to(source_root)
        for idx, (start, end, body) in enumerate(iter_asy_blocks(tex), 1):
            comments = re.findall(r"/\*(.*?)\*/", body, re.S)
            preserved = None
            has_placeholder = False
            for comment in comments:
                if "Source generated by TSQ" in comment:
                    has_placeholder = True
                extracted = extract_tsqx_from_comment(comment)
                if extracted:
                    preserved = extracted
                    break

            caption = nearest_caption(tex, end)
            item = {
                "source_tex": str(relative),
                "asy_index": idx,
                "caption": caption,
            }

            if preserved is None:
                if has_placeholder:
                    item["status"] = "placeholder_only"
                else:
                    item["status"] = "no_tsqx_comment"
                manifest.append(item)
                continue

            stem_parts = [relative.stem, f"{idx:02d}"]
            if caption:
                stem_parts.append(slugify(caption)[:50])
            out_name = "-".join(filter(None, stem_parts)) + ".tsqx"
            out_path = extracted_dir / out_name
            out_path.write_text(preserved, encoding="utf-8")

            item["status"] = "extracted"
            item["output_file"] = str(out_path.relative_to(output_root))
            manifest.append(item)

    (output_root / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    extracted_count = sum(1 for x in manifest if x["status"] == "extracted")
    placeholder_count = sum(1 for x in manifest if x["status"] == "placeholder_only")
    print(f"[OK] Wrote manifest with {len(manifest)} entries")
    print(f"[OK] Extracted {extracted_count} TSQX snippets")
    print(f"[OK] Found {placeholder_count} placeholder-only figures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
